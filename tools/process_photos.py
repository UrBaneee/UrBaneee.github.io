"""Prepare a folder of photos for one city on the Journey map.

Usage:
    python3 tools/process_photos.py <city-key> <folder-of-jpg-or-png> [--years 2019-2019] [--map map.json]

  --years   only trust capture dates in this range (screenshots and edits often
            carry the date they were saved, not the date the photo was taken)
  --map     write {original filename: index} to this file, for choosing covers
            and keepers. Keep it out of the website folder.

HEIC files must be converted to JPEG first, for example on macOS:
    sips -s format jpeg IMG_1234.HEIC --out IMG_1234.jpg

For each photo this:
  * applies the camera's rotation, then saves a fresh JPEG with no metadata,
    so location (GPS), camera and other EXIF data are not published;
  * writes a large version (1600px long edge) and a thumbnail (480px);
  * names files by capture date (<city>-01.jpg, ...), never by original filename;
  * records the capture date (if any) and size in photos.js for the website.
"""
import argparse
import datetime
import json
import os
import re

from PIL import Image, ImageOps

SITE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LARGE, THUMB = 1600, 480


# timestamps written by an editing/export app, not by a camera
BOGUS_TIMESTAMPS = {"2026:06:30 18:34:00"}


def capture_date(im, name, years):
    exif = im.getexif()
    raw = exif.get_ifd(0x8769).get(36867) or exif.get(306) or ""
    date = None
    m = re.match(r"(\d{4}):(\d{2}):(\d{2})", raw)
    if m and raw.strip() not in BOGUS_TIMESTAMPS:
        date = f"{m[1]}-{m[2]}-{m[3]}"
    if not date:
        # some apps put a millisecond timestamp or a date in the file name
        ms = re.search(r"(1[3-9]\d{11})", name)
        ymd = re.search(r"(20\d{2})-(\d{2})-(\d{2})", name)
        if ms:
            date = datetime.datetime.utcfromtimestamp(int(ms[1]) / 1000).strftime("%Y-%m-%d")
        elif ymd:
            date = f"{ymd[1]}-{ymd[2]}-{ymd[3]}"
    if date and years and not (years[0] <= int(date[:4]) <= years[1]):
        date = None
    return date


def main(city, src, years=None, map_file=None):
    out_dir = os.path.join(SITE, "photos", city)
    os.makedirs(out_dir, exist_ok=True)
    for old in os.listdir(out_dir):
        if old.startswith(city + "-"):
            os.remove(os.path.join(out_dir, old))

    items = []
    for name in os.listdir(src):
        if name.startswith(".") or not name.lower().endswith((".jpg", ".jpeg", ".png")):
            continue
        im = Image.open(os.path.join(src, name))
        items.append((capture_date(im, name, years) or "9999", name))
    items.sort()

    photos = []
    index = {}
    for i, (date, name) in enumerate(items, 1):
        index[name] = i - 1
        im = ImageOps.exif_transpose(Image.open(os.path.join(src, name))).convert("RGB")
        base = f"{city}-{i:02d}"
        large = im.copy()
        large.thumbnail((LARGE, LARGE), Image.LANCZOS)
        large.save(os.path.join(out_dir, base + ".jpg"), "JPEG", quality=82, optimize=True, progressive=True)
        thumb = im.copy()
        thumb.thumbnail((THUMB, THUMB), Image.LANCZOS)
        thumb.save(os.path.join(out_dir, base + "-t.jpg"), "JPEG", quality=76, optimize=True)
        photos.append({
            "src": f"photos/{city}/{base}.jpg",
            "thumb": f"photos/{city}/{base}-t.jpg",
            "w": large.width,
            "h": large.height,
            "date": None if date == "9999" else date,
        })

    data_file = os.path.join(SITE, "photos.js")
    data = {}
    if os.path.exists(data_file):
        m = re.search(r"window\.PHOTOS = (\{.*\});", open(data_file, encoding="utf-8").read(), re.S)
        if m:
            data = json.loads(m.group(1))
    data[city] = photos
    with open(data_file, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/process_photos.py. Photos for each city on the Journey map.\n")
        f.write("window.PHOTOS = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")
    if map_file:
        with open(map_file, "w", encoding="utf-8") as f:
            json.dump(index, f, indent=1)
    dated = sum(1 for p in photos if p["date"])
    print(f"{city}: {len(photos)} photos written to photos/{city}/ ({dated} with a date)")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("city")
    ap.add_argument("folder")
    ap.add_argument("--years", help="e.g. 2019-2019")
    ap.add_argument("--map")
    a = ap.parse_args()
    yrs = tuple(int(y) for y in a.years.split("-")) if a.years else None
    main(a.city, a.folder, yrs, a.map)
